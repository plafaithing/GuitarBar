    '和弦/双音在同拍输出多个不同弦的音（不是同弦重复）。'
    '7.无法确定的音宁可整小节给低 confidence，也不要猜测编造。'
    '8.拍弦、密集和弦、复杂连音区 confidence 给低于 0.6。'
    '9.反复记号与跳转顺序只记一遍内容；歌词、和弦名、指法标注、水印一律忽略。';

String tabUserPrompt({
  required List<String> tuning,
  required String timeSignature,
  required int page,
  required int total,
}) =>
    '调弦兜底（仅谱面无调弦标注时使用，从6弦到1弦低到高）：${tuning.join(', ')}。'
    '谱面标注了调弦则以谱面为准、写入 JSON tuning 字段，忽略此兜底值。'
    '变调夹：从谱面标注识别并在 JSON capo 字段报告，无标注填 0。'
    '拍号：$timeSignature（每小节 ${timeSignature.split('/')[0]} 拍）。'
    '本页为第 ${page + 1}/$total 页。';
